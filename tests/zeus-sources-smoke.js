const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const context=vm.createContext({zeusEscape:s=>String(s).replaceAll('<','&lt;'),zeusUI:{},$:()=>null});
vm.runInContext(fs.readFileSync('public/zeus-sources.js','utf8'),context);
const html=context.zeusSourcesSection({fuentesAutomaticas:[{sucursal:'Norte<script>',movimiento:'ENTRADA_MERCANCIA',fuente:'13',serie:'00',usuarios:[7]}]});
assert.match(html,/Fuentes por sucursal/);assert.match(html,/Norte&lt;script>/);assert.match(html,/value="13"/);
assert.match(html,/name="sourceUnit"/);assert.match(html,/name="sourceDocument"/);
const ui=fs.readFileSync('public/zeus.js','utf8');
assert.match(ui,/Fuentes de Zeus por sucursal/);assert.doesNotMatch(ui,/Destino y comprobante/);
assert.equal((ui.match(/zeusSourcesSection\(s\)/g)||[]).length,1);
assert.doesNotMatch(ui,/zeusField\('Fuente|zeusField\('Serie|zeusField\('Unidad de negocio|zeusField\('Tipo de factura/);
context.zeusUI.settings={unidadNegocio:'LEGADO',tipoFactura:'FA'};
assert.match(context.zeusSourceRow({}),/value="LEGADO"/);
assert.match(context.zeusSourceRow({unidadNegocio:'NORTE',tipoFactura:'FC'}),/value="NORTE"/);
assert.doesNotMatch(html,/sourceUsers|sourceScope|Predeterminada/);
assert.doesNotMatch(html,/preparación/);
for(const label of ['Facturación','Recibo de caja','Comprobante de egreso'])assert.ok(html.includes('>'+label+'</option>'));
assert.equal(context.zeusReadSources({fuentesAutomaticas:null}),null);
vm.runInContext("zeusSourceBranches=[{id:3,codigo:'01',nombre:'Principal',activa:true},{id:4,codigo:'02',nombre:'Inactiva',activa:false},{id:5,codigo:'03',nombre:'Norte',activa:true}]",context);
assert.match(context.zeusSourceRow({sucursalId:3}),/value="3" selected/);
assert.doesNotMatch(context.zeusSourceRow({}),/>02 · Inactiva/);
const row=branch=>({querySelector:selector=>({value:({sourceBranch:branch,sourceMovement:'ENTRADA_MERCANCIA',sourceCode:'12',sourceSeries:'00',sourceUnit:'Norte',sourceDocument:'FA'})[selector.slice(6,-1)]})});
context.$=()=>({});context.document={querySelectorAll:()=>[row('3'),row('5')]};
assert.equal(context.zeusReadSources({})[0].sucursalId,3);assert.equal(context.zeusReadSources({})[0].usuarios.length,0);
assert.equal(context.zeusReadSources({})[0].unidadNegocio,'Norte');assert.equal(context.zeusReadSources({})[0].tipoFactura,'FA');
context.document.querySelectorAll=()=>[row('3'),row('3')];assert.throws(()=>context.zeusReadSources({}),/sucursal y movimiento/);
context.document.querySelectorAll=()=>[row('4')];assert.throws(()=>context.zeusReadSources({}),/activa/);
console.log('Fuentes por sucursal: sin usuarios, selector y duplicados validados.');
