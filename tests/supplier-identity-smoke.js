const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {DOMParser,Node}=require('@xmldom/xmldom');
const source=fs.readFileSync('public/app.js','utf8');
const context=vm.createContext({DOMParser,Node});
vm.runInContext(source.slice(source.indexOf('function localName'),source.indexOf('function inferType')),context);
const parse=(type,person,dv='4')=>context.extractParty(new DOMParser().parseFromString(`<Invoice><AccountingSupplierParty>${person==null?'':`<AdditionalAccountID>${person}</AdditionalAccountID>`}<Party><PartyTaxScheme><CompanyID ${type==null?'':`schemeName="${type}"`} schemeID="${dv}">900123456</CompanyID></PartyTaxScheme></Party></AccountingSupplierParty><AccountingCustomerParty><AdditionalAccountID>1</AdditionalAccountID></AccountingCustomerParty></Invoice>`,'application/xml').documentElement,'AccountingSupplierParty');
for(const [code,expected] of Object.entries({'31':'NIT','13':'CC','22':'CE','11':'RC','12':'TI','21':'TE','41':'PAS','42':'DE','43':'OTRO','50':'NITEXT','91':'NUIP'}))assert.equal(parse(code,'2').identificationType,expected);
assert.equal(context.resolvedSupplierPersonType(parse('31','2')),'N');
assert.equal(context.resolvedSupplierPersonType(parse('31','1')),'J');
for(const person of [null,'','3'])assert.equal(context.resolvedSupplierPersonType(parse('31',person)),'');
assert.equal(context.resolvedSupplierPersonType(parse('13','1')),'');
assert.equal(parse(null,'1','31').identificationType,'','El DV no es un tipo de identificación');
assert.equal(parse('99','1').identificationType,'');
const missing=parse('31',null);
assert.throws(()=>context.requireSupplierIdentity(missing),/Confirma/);
missing.xmlFields.NexoPersonConfirmation={type:'N',identification:missing.identification,identificationType:'NIT'};
context.requireSupplierIdentity(missing);
assert.equal(context.resolvedSupplierPersonType(missing),'N');
assert.equal(missing.xmlFields.AdditionalAccountID,undefined,'No se inventa un campo original del XML');
missing.identification='otro';assert.throws(()=>context.requireSupplierIdentity(missing),/Confirma/);
assert.equal(context.supplierPersonType({AdditionalAccountID:[{value:'1'},{value:'2'}]}),'');
console.log('Identidad proveedor: tipos independientes, ausencia, contradicción y confirmación verificados.');
